// Builds the Library from the curated entries (library_entries.mjs): each entry's patch is applied to a FRESH config (so a preset never
// inherits the settings of whoever loads it) and the full, validated config is written to
//   src/presets/library.js          the data the Presets panel shows
//   presets/proun-library.json      the same as an importable file (Presets > Import)
//   node tools/presets/build_library.mjs
import fs from 'node:fs';
import { createSceneConfig } from '../../src/config/SceneConfig.js';
import { appConfigContext } from '../../src/config/store.js';
import { ENTRIES } from './library_entries.mjs';

const root = new URL('../../', import.meta.url);
export function buildRecords() {
  return ENTRIES.map((e) => {
    const fresh = createSceneConfig(appConfigContext);
    fresh.replace(e.patch);
    return { id: e.id, ref: e.ref, name: e.name, after: e.after, note: e.note, config: fresh.toJSON() };
  });
}
if (import.meta.url === `file://${process.argv[1]}`) {
  const records = buildRecords();
  const js = `// GENERATED by tools/presets/build_library.mjs from tools/presets/library_entries.mjs: do not edit by hand.
// The built-in Library of the Presets panel: ${records.length} compositions after Lissitzky's Prouns. Each \`config\` is a complete SceneConfig
// (loaded with SceneConfig.replace); \`after\` says what it is after, \`note\` how close it is.
export const LIBRARY = ${JSON.stringify(records, null, 2)};
`;
  fs.writeFileSync(new URL('src/presets/library.js', root), js);
  fs.mkdirSync(new URL('presets/', root), { recursive: true });
  const json = records.map((r) => ({ id: r.id, name: r.name, createdAt: '2026-10-28T00:00:00.000Z', ...r.config }));
  fs.writeFileSync(new URL('presets/proun-library.json', root), JSON.stringify(json, null, 2) + '\n');
  console.log(`wrote ${records.length} presets`);
}
